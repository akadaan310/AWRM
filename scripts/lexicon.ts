/** Generates research/lexicon.json and research/LEXICON.md from packages/core/src/lexicon.ts. */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { EXTERNAL_VOCABULARY, LEXICON } from '@awrm/core';

export function lexiconJson(): string {
  return JSON.stringify({ schema: 'awrm.lexicon/1', generatedFrom: 'packages/core/src/lexicon.ts', terms: LEXICON, externalVocabularies: EXTERNAL_VOCABULARY }, null, 2) + '\n';
}

export function lexiconMarkdown(): string {
  const rows = LEXICON.map((e) => `| \`${e.id}\` | **${e.name}** | ${e.definition} | ${e.example} | \`${e.artifact}\` | ${e.falsifier} | ${e.tests.map((t) => `\`${t}\``).join('<br>')} |`);
  return [
    '# AWRM Lexicon',
    '',
    '<!-- GENERATED by `node --import tsx scripts/lexicon.ts` from packages/core/src/lexicon.ts. Do not edit by hand; tests/core/lexicon.test.ts fails on drift. -->',
    '',
    'The twelve terms below are the complete AWRM controlled vocabulary. Each has a TypeScript type (`packages/core/src/types.ts` or the named artifact), a JSON Schema (in `research/lexicon.json`), a worked real-world example, positive and negative tests, and a falsifier. Common computer-science words used elsewhere do not redefine these terms.',
    '',
    '| id | name | definition | real-world example | artifact | falsifier | tests |',
    '|---|---|---|---|---|---|---|',
    ...rows,
    '',
    '## External vocabularies (reference only — not AWRM terms)',
    '',
    ...Object.entries(EXTERNAL_VOCABULARY).map(([k, v]) => `- **${k.toUpperCase()}**: ${v.map((x) => `\`${x}\``).join(', ')}`),
    '',
    'Collision rule: no AWRM id (after the `awrm.` prefix) or name equals any of the terms above (enforced by `tests/core/lexicon.test.ts` and `awrm audit`).',
    '',
  ].join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const root = join(import.meta.dirname, '..');
  writeFileSync(join(root, 'research', 'lexicon.json'), lexiconJson());
  writeFileSync(join(root, 'research', 'LEXICON.md'), lexiconMarkdown());
  console.log('wrote research/lexicon.json and research/LEXICON.md');
}
